let currentLang = localStorage.getItem('shopnav_lang') || 'en';

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('shopnav_lang', lang);
  if (typeof localizeData === 'function') {
    localizeData();
  }
  updateStaticTexts();
  
  // Dispatch event for dynamic re-renders
  window.dispatchEvent(new Event('languageChanged'));
}

function t(key) {
  if (typeof I18N === 'undefined') return key;
  const lang = typeof currentLang !== 'undefined' ? currentLang : 'en';
  const langObj = I18N[lang] || I18N['en'] || {};
  const englishObj = I18N['en'] || {};
  return langObj[key] || englishObj[key] || key;
}

function updateStaticTexts() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.innerHTML = t(key);
  });
  
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', t(key));
  });

  // Update language selector UI
  const langBtn = document.getElementById('langSelectorLabel');
  if (langBtn) {
    const flags = { en:'🇬🇧', ru:'🇷🇺', kk:'🇰🇿', ko:'🇰🇷' };
    langBtn.textContent = `${flags[currentLang]} ${currentLang.toUpperCase()}`;
  }
}

